// Generates the dotted land map used in the hero (lib/map-data.ts).
// Run with: npm run map
import { readFileSync, writeFileSync } from 'node:fs';
import { geoContains, geoEquirectangular } from 'd3-geo';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);

// Region: West Africa to East Asia, equator to the Arctic coast of Russia
export const BOUNDS = { west: -20, east: 112, south: 2, north: 72 };
const W = 1000;
const lonSpan = BOUNDS.east - BOUNDS.west;
const scale = W / ((lonSpan * Math.PI) / 180);
const H = Math.round(scale * (((BOUNDS.north - BOUNDS.south) * Math.PI) / 180));
const projection = geoEquirectangular()
  .scale(scale)
  .translate([0, 0])
  .center([0, 0]);
// manual offset so that (west, north) maps to (0, 0)
const [ox, oy] = projection([BOUNDS.west, BOUNDS.north]);

const step = 1.05; // degrees between dots
let d = '';
let count = 0;
for (let lat = BOUNDS.north - step / 2; lat > BOUNDS.south; lat -= step) {
  // keep dots roughly evenly spaced on screen (equirectangular, so constant)
  for (let lon = BOUNDS.west + step / 2; lon < BOUNDS.east; lon += step) {
    if (geoContains(land, [lon, lat])) {
      const [x, y] = projection([lon, lat]);
      d += `M${(x - ox).toFixed(1)} ${(y - oy).toFixed(1)}h0`;
      count++;
    }
  }
}

const out = `// AUTO-GENERATED by scripts/build-map.mjs — do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const MAP_BOUNDS = ${JSON.stringify(BOUNDS)};
export const MAP_SCALE = ${scale};
export const LAND_DOTS = ${JSON.stringify(d)};
`;
writeFileSync(new URL('../lib/map-data.ts', import.meta.url), out);
console.log(`map: ${count} dots, ${W}x${H}, ${(out.length / 1024).toFixed(1)} KB`);
