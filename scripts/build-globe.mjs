// Generates lib/globe-data.ts: a land mask over an evenly spaced (Fibonacci) set of
// points on the sphere. The browser rebuilds the point positions from the index, so
// the file only stores 1 bit per point (~4 KB). Run with: npm run globe
import { readFileSync, writeFileSync } from 'node:fs';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);

export const N = 26000;
const GOLDEN = Math.PI * (3 - Math.sqrt(5));
const bytes = new Uint8Array(Math.ceil(N / 8));
let count = 0;
for (let i = 0; i < N; i++) {
  const y = 1 - ((i + 0.5) * 2) / N;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = (((i * GOLDEN) * 180) / Math.PI) % 360;
  if (lon > 180) lon -= 360;
  if (lat < -60) continue; // skip Antarctica — never in view and adds noise
  if (geoContains(land, [lon, lat])) {
    bytes[i >> 3] |= 1 << (i & 7);
    count++;
  }
}
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync(
  new URL('../lib/globe-data.ts', import.meta.url),
  `// AUTO-GENERATED by scripts/build-globe.mjs — do not edit by hand.\nexport const GLOBE_N = ${N};\nexport const GLOBE_LAND_MASK = '${b64}';\n`,
);
console.log(`globe: ${count} land points of ${N}, mask ${(b64.length / 1024).toFixed(1)} KB`);
